/* VectorMember: 16 字节内嵌容器 (hdr, _Myfirst, _Mylast, _Myend) */

/* LevelObj —— m[0] 元素, 0xA0 字节 [A] */
typedef struct LevelObj {   /* stride 0xA0 */
    int   pos;          /* +0x00  1 基位置 (引擎出参下标 = pos-1) [A] */
    int   idxA;         /* +0x04  (wnwr 用) */
    int   idxB;         /* +0x08  (wnwr 用) */
    float low;          /* +0x0C  (wnwr 卖出价源) */
    float high;         /* +0x10  (wnwr 买入价源) */
    /* ... */
    int   m24;          /* +0x24  ★ CHDUAN 导出值 {-2,-1,1,2} [A] */
    /* ... */
    int   m84;          /* +0x84  ★ {1,2} (供其他 CH* 函数) [A] */
    /* ... */
} LevelObj;

/* CandItem —— m[2]/m[3] 元素, 0x28 字节 [A] */
typedef struct CandItem {   /* stride 0x28 */
    int   pad0;         /* +0x00 */
    int   idxA;         /* +0x04  索引 A (引用 m[0]) ★+1 分支取此 */
    int   idxB;         /* +0x08  索引 B (引用 m[0]) ★-1/-2 分支取此 */
    float f_c;          /* +0x0C  价格 1 (与 low 同序) */
    float f_10;         /* +0x10  价格 2 (与 high 同序) */
    int   pad14;        /* +0x14 */
    int   flag18;       /* +0x18  标志 {-1,+1}  驱动 -1/+1 标记循环 */
    /* +0x1C..+0x24 待第三批 */
} CandItem;

/* ---------------------------------------------------------------------------
 * 1. 包装层 CalcProc_ChDuan @0x1000f850  [A]
 * -------------------------------------------------------------------------*/
bool CalcProc_ChDuan(TAF_Calculator* self /*ecx*/, int count, double* out, ...)
{
    /* 惰性上下文: 46 个 CalcProc_Ch* 共享同款 */
    if (self->ctx == NULL) {                     /* [self+0xB0] */
        h = new(4);
        h->W = W_ctor(new(0xC8));                /* 0x1002c160 -> 0x1003d910 */
        self->ctx = h;
    }
    /* 无 Authorize —— 本函数不做任何授权检查 [A] */
    sub_1002c710(count, self->ctx, out, wrap_obj);   /* 引擎 */
    return true;
}

/* ---------------------------------------------------------------------------
 * 2. 引擎 sub_1002c710  [A] (113 条指令, 唯一调用者 = 本包装层)
 * -------------------------------------------------------------------------*/
int sub_1002c710(int count, CtxHandle* ctx, double* out, void* obj)
{
    if (count <= 0) return 0;
    if (obj == NULL) return 0;

    W* w = ctx->W;
    sub_10053540(w);                 /* ★ 准备阶段 (§3), W->m[0] 在此被打好标记 */

    /* 快照 W->m[0] (0x1003f150 -> vector 拷贝构造 0x1006a4e0) */
    Vec snapshot = copy_ctor(w);     /* 因 m[0] 位于 W+0x00, 以 W 指针即拷贝 m[0] */

    memset(out, 0, count * sizeof(double));
    int cursor = 0;
    for (CandItem_like* it = snapshot.begin; it != snapshot.end; it = it + 0xA0) {
        int   pos = ((LevelObj*)it)->pos - 1;      /* 1 基 -> 0 基 [A] */
        int   val = ((LevelObj*)it)->m24;          /* +0x24 标记值 [A] */
        while (cursor < pos) out[cursor++] = 0.0;  /* 空隙补 0 */
        out[cursor++] = (double)val;               /* x87 fild/fstp [A] */
    }
    free(snapshot);
    return 0;
}

/* ---------------------------------------------------------------------------
 * 3. 准备 sub_10053540(W)  [A/B/C 标注]
 * -------------------------------------------------------------------------*/
void sub_10053540(W* w)
{
    /* --- 3.1 序言门控 [A] --- */
    if (w->m[0]._Myfirst == NULL) return;
    int n = (w->m[0]._Mylast - w->m[0]._Myfirst) / sizeof(LevelObj);
    if (n <= 21) return;                      /* ★ 少于 22 个级别对象 → 放弃 */
    sub_1003eba0(w);                          /* 拆表: m[5] -> m[2]/m[3]  (§3.0) [A] */

    /* --- 3.0 拆表 sub_1003eba0(W) @0x1003eba0 [A] ------------------------- */
    /*  1) 压缩 m[2] (W+0x24/+0x28) 与 m[3] (W+0x34/+0x38): __move(0x1006b050) 收尾
     *  2) push 2; m[0].begin()+2  (跳过前两个级别对象)
     *  3) for (it = m[5].begin ~ m[5].end; it += 0x28):        // 唯一源 = W+0x50
     *         it[+0x20] = 0
     *         if (it[+0x14] == +1) { cnt++;                        // 底分型
     *             m0[ it[+0x04] ].+0x20 =  1;  m0[ it[+0x08] ].+0x20 = -1;
     *             push_back(m[3], {cnt, it[+4], it[+8], it[+0C], it[+10], +1, 0, it[+1C], it[+20]});
     *         } else if (it[+0x14] == -1) { cnt++;                 // 顶分型
     *             m0[ it[+0x04] ].+0x20 =  1;  m0[ it[+0x08] ].+0x20 = -1;
     *             push_back(m[2], {cnt, it[+4], it[+8], it[+0C], it[+10], -1, 0, it[+1C], it[+20]});
     *         }
     *  ContA = m[2](W+0x20) <- 顶分型;  ContB = m[3](W+0x30) <- 底分型。
     *  同容器内保持 m[5] 原序 -> 拆表顺序对 prep 结果不敏感 (docs/24 §8) [B]
     * --------------------------------------------------------------------- */

    /* --- 3.2 四个内联实例 (跳板 0x100535d2 + 阶段选择器 esi) [A] ---------- */
    /*  选择器: esi=0 -> ①(扫 m[2]) ; esi=1 -> ③(扫 m[3]) ; esi=-1 -> ④(扫 m[2])
     *          ② 仅由 ① 在 m[2] 走完时进入 (0x10053646 je 0x10053db2)，走完后
     *          在 0x10054622/0x1005465e 写 m[3] 项 +0x18 = -1/+1 并置 esi=1/-1。
     *  每实例 4 组 0x28 字节栈缓存 (rep movsd 0xa):
     *      cacheA [esp+0x68] / cacheB [esp+0x90]  —— 外层容器的 prev / cur
     *      cacheC [esp+0xd0] / cacheD [esp+0xf8]  —— 内层候选端点 (迭代器 [esp+0x120]) 的 prev / cur
     *  标志: [0x1f] 首项标志; [0x12]/[0x13] 两态推进; [0x1e]/[0x1c]/[0x1d] 包含关系三态(一位热)
     *  ①④ = 顶/上行侧 (首判 test ah,0x5/jp, cache*.H 主导)
     *  ②③ = 底/下行侧 (首判 test ah,0x41/jne, cache*.L 主导)
     *  → ①② 与 ③④ 互为镜像; ② 与 ③ 同形; ④ = ② 的二态退化版。 [B]
     * --------------------------------------------------------------------- */

    instance1:
    for (it = w->m[2].begin; it != w->m[2].end; it += 0x28) {   /* [B] */
        /* --- 与缓存项的单调性/包含关系判定 (x87) --- */
        /* 若 cached.low < cur.low && cached.high < cur.high        -- 整体更高 */
        /*     -> 缓存项 := cur; [0x12]=0; [0x13]=1; 退出本实例       [B] */
        /* 若 cached.low > cur.low && cached.high > cur.high        -- 整体更低 */
        /*     -> 仅更新 [esp+0xa0] := cur.high; 退出                  [B] */
        /* 若 cached.low >= cur.low (单边)                           -- 包含/交错 */
        /*     -> 缓存项 := cur; [0x13]=1; 走 continue 出口            [B] */
        /* [esp+0x12]==0 时走另一支: 与缓存项自身字段(cacheItem.c/10) */
        /* [esp+0x12]==0 支路 -> 0x10053c86 包含关系处理核 (§3.2b)      [B] */
    }
    /* --- 3.2b 包含关系处理核 0x10053c86 / 0x10053c84 [B] ---
     *   if (cur.H > cacheA.H) goto L2;            // test ah,0x5 / jp
     *   if (cur.L > cacheA.L) goto L2;
     *   cacheB := cacheA; cacheA := cur;  iterpair := {ebp,cur};  // 整体替换
     *   L2: if (cacheA.H > cur.H) goto L3;        // 仅低点单边刷新
     *       cacheA.L := cur.L;                    // (保高、刷低)
     *   L3: cacheB := cacheA; cacheA := cur; iterpair := {ebp,cur};
     *   出口统一 jmp 0x10053d73 (循环步进: it += 0x28; jmp 0x1005361c)
     * --------------------------------------------------------------------- */

    /* --- 3.3 标记阶段 [A] —— 全部写入 W->m[0][idx].+0x24 --- */
    /*  x87 精确语义（Intel 原义; 41h+jne 落空 = ST0>ST1）:
     *    test ah,0x41;jne 跳 = {<,=,U}   落 = {>}
     *    test ah,0x41;je  跳 = {>}      test ah,0x05;jp 跳 = {>=} 落 = {<}
     *    test ah,0x01;jne 跳 = {<,U}
     *  （U=不可比, 正常价格数据不会出现） */
    if (flag13) {                                     /* [esp+0x13]==1 */
        CandItem* prev = (CandItem*)(w->m[2]._Mylast - 0x28);   /* m[2] 末项 */
        /* fld prev[+0x10]; fld cur[+0x10]; fcompp -> ST0=cur,ST1=prev */
        if (prev->idxB > cur->idxB && cur->f_10 > prev->f_10)
            w->m[0][ prev->idxB ].m24 = -2;           /* @10055d46 用 prev[+X08] */
        else
            w->m[0][ cur->idxB ].m24  = -2;           /* @10055d88 用 cur[+X08] */
    }
    /* +2 块: base = 迭代器对 [esp+0x34/0x38]; fld cur[+0xC]; fld base[+0xC] */
    /*         fcompp -> ST0=base,ST1=cur; 05h+jp 跳 = base>=cur, 落 = base<cur */
    if (cond2) {
        int idx;
        if (cur->idxA > base->idxA && base->f_c < cur->f_c) idx = cur->idxA;
        else                                               idx = base->idxA;
        w->m[0][ idx ].m24 = +2;                      /* @10055e8a */
    }

    for (it = w->m[3].begin; it != w->m[3].end; it += 0x28)
        if (it->flag18 == -1)
            w->m[0][ it->idxB ].m24 = -1;             /* @10055f2f */

    for (it = w->m[2].begin; it != w->m[2].end; it += 0x28)
        if (it->flag18 == +1)
            w->m[0][ it->idxA ].m24 = +1;             /* @10055fd7 */

    /* --- 3.4 实例尾部 +0x84 写入 (四个发布块) [A] --- */
    /*  序号规律 = 容器(2/3) x 索引字段(B:+0x08 / A:+0x04)                */
    /*    ④ 尾发布块 (0x10055b48 -> 0x10055c68, 走 m[2]):
     *        m[0][ cur_m2[+0x08] ].m84 = 1   (@10055bfa)  ; 另 [cur+0x18]=+1 @10055b63
     *        m[0][ cur_m2[+0x04] ].m84 = 2   (@10055c3f)  ; [esp+0x128] = cur[+0x0C]
     *    ③ 尾发布块 (0x10055099 -> 0x1005515f, 走 m[3]):
     *        m[0][ cur_m3[+0x08] ].m84 = 3   (@10055105)  ; [esp+0x158] = cur[+0x10]
     *        m[0][ cur_m3[+0x04] ].m84 = 4   (@10055151)
     *  [勘误] docs/16 §2.3 记 +0x84 ∈ {1,2}; 实测 {1,2,3,4}。                  */
}

